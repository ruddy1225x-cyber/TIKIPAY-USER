// ======================================================
// TRADUCIR TEXTO
// ======================================================

function translateText(
  text
) {

  if (!text) {
    return text;
  }


  if (
    window.tikiPayLanguage === "es"
  ) {
    return text;
  }


  const dictionary =
    TIKIPAY_TRANSLATIONS[
      window.tikiPayLanguage
    ];


  if (!dictionary) {
    return text;
  }


  return (
    dictionary[text] ||
    text
  );

}


// Helper global para otros JS
window.tikiT =
  function (text) {

    return translateText(
      text
    );

  };


// ======================================================
// TRADUCIR NODOS DE TEXTO
// ======================================================

function translateTextNodes(
  root = document.body
) {

  if (
    !root ||
    window.tikiPayLanguage === "es"
  ) {
    return;
  }


  const walker =
    document.createTreeWalker(
      root,
      NodeFilter.SHOW_TEXT
    );


  const nodes =
    [];


  while (
    walker.nextNode()
  ) {

    const node =
      walker.currentNode;


    const original =
      node.nodeValue
        ?.trim();


    if (original) {

      nodes.push(
        node
      );

    }

  }


  nodes.forEach(
    node => {

      const value =
        node.nodeValue;


      const trimmed =
        value.trim();


      const translated =
        translateText(
          trimmed
        );


      if (
        translated === trimmed
      ) {
        return;
      }


      const leftWhitespace =
        value.match(
          /^\s*/
        )?.[0] || "";


      const rightWhitespace =
        value.match(
          /\s*$/
        )?.[0] || "";


      node.nodeValue =
        leftWhitespace +
        translated +
        rightWhitespace;

    }
  );

}


// ======================================================
// TRADUCIR ATRIBUTOS
// ======================================================

function translateAttributes(
  root = document
) {

  if (
    !root ||
    window.tikiPayLanguage === "es"
  ) {
    return;
  }


  /*
    Si recibimos document funciona directamente.
    Si recibimos un elemento también.
  */

  const elements =
    root.querySelectorAll
      ? root.querySelectorAll(
          `
          input[placeholder],
          textarea[placeholder],
          [aria-label],
          [title]
          `
        )
      : [];


  elements.forEach(
    element => {

      [
        "placeholder",
        "aria-label",
        "title"
      ]
        .forEach(
          attribute => {

            const value =
              element.getAttribute(
                attribute
              );


            if (!value) {
              return;
            }


            const translated =
              translateText(
                value
              );


            if (
              translated !==
              value
            ) {

              element.setAttribute(
                attribute,
                translated
              );

            }

          }
        );

    }
  );

}


// ======================================================
// APLICAR TRADUCCIONES A TODA LA PÁGINA
// ======================================================

window.applyTikiPayTranslations =
  function () {

    document.documentElement.lang =
      window.tikiPayLanguage;


    if (
      window.tikiPayLanguage === "es"
    ) {

      return;
    }


    translateTextNodes(
      document.body
    );


    translateAttributes(
      document
    );

  };


// ======================================================
// OBTENER IDIOMA DEL USUARIO
// ======================================================

async function loadTikiPayLanguage() {

  let language =
    localStorage.getItem(
      "tikipay_language"
    )
    || "es";


  try {

    if (
      window.supabaseClient
    ) {

      const {
        data: {
          session
        },
        error: sessionError
      } =
        await window
          .supabaseClient
          .auth
          .getSession();


      if (sessionError) {

        console.warn(
          "No se pudo leer la sesión para idioma:",
          sessionError
        );

      }


      if (session) {

        const {
          data: profile,
          error: profileError
        } =
          await window
            .supabaseClient
            .from("profiles")
            .select(
              "language"
            )
            .eq(
              "id",
              session.user.id
            )
            .single();


        if (profileError) {

          console.warn(
            "No se pudo cargar el idioma del perfil:",
            profileError
          );

        }


        if (
          profile?.language
        ) {

          language =
            profile.language;

        }

      }

    }

  } catch (error) {

    console.warn(
      "No se pudo cargar el idioma:",
      error
    );

  }


  /*
    Solo aceptamos idiomas soportados.
  */

  if (
    language !== "en" &&
    language !== "es"
  ) {

    language =
      "es";

  }


  window.tikiPayLanguage =
    language;


  localStorage.setItem(
    "tikipay_language",
    language
  );


  window.applyTikiPayTranslations();

}


